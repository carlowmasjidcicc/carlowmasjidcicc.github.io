export function addDays(date: string, amount: number): string {
  const parsed = new Date(`${date}T00:00:00Z`);
  parsed.setUTCDate(parsed.getUTCDate() + amount);
  return parsed.toISOString().slice(0, 10);
}

export function getMonthDays(month: string): PrayerDay[] {
  return prayerTimetable.filter((day) => day.date.startsWith(month));
}

export function getWeekDays(date: string): PrayerDay[] {
  const parsed = new Date(`${date}T00:00:00Z`);
  const dayOfWeek = parsed.getUTCDay();
  const mondayOffset = dayOfWeek === 0 ? -6 : 1 - dayOfWeek;
  const monday = addDays(date, mondayOffset);

  return Array.from({ length: 7 }, (_, index) =>
    prayerTimetableByDate.get(addDays(monday, index)),
  ).filter((day): day is PrayerDay => Boolean(day));
}
